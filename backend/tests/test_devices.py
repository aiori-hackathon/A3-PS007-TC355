"""
Test Device Initialisation and Address Rotation
Verifies that 5 simulated IoT devices are initialised per tenant,
and that temporary SLAAC IPv6 address rotation succeeds without false alerts.
"""
import unittest
import sqlite3
from backend.database import init_db, get_db_connection
from backend.services.network_simulator import NetworkSimulator
from backend.services.ipv6_address_service import IPv6AddressService

class TestDevices(unittest.TestCase):
    def setUp(self):
        self.conn = get_db_connection(":memory:")
        init_db(self.conn)
        self.simulator = NetworkSimulator()

    def tearDown(self):
        self.conn.close()

    def test_five_devices_initialised(self):
        """TEST 1: Verify that exactly five simulated devices are created per tenant."""
        cur = self.conn.cursor()
        cur.execute("SELECT COUNT(*) FROM devices WHERE tenant_id = 'tenant-alpha'")
        alpha_count = cur.fetchone()[0]
        self.assertEqual(alpha_count, 5, "Tenant Alpha should have exactly 5 simulated IoT devices.")

        cur.execute("SELECT COUNT(*) FROM devices WHERE tenant_id = 'tenant-beta'")
        beta_count = cur.fetchone()[0]
        self.assertEqual(beta_count, 5, "Tenant Beta should have exactly 5 simulated IoT devices.")

        # Verify device properties
        cur.execute("SELECT device_id, device_name, current_ipv6, current_pseudonym, status FROM devices WHERE tenant_id = 'tenant-alpha'")
        rows = cur.fetchall()
        for r in rows:
            self.assertTrue(r["current_ipv6"].startswith("2001:db8:1::"), "Device must have documentation prefix IPv6")
            self.assertTrue(r["current_pseudonym"].startswith("DEV-"), "Device must have a privacy pseudonym")
            self.assertEqual(r["status"], "CONNECTED")

    def test_temporary_address_rotation(self):
        """TEST 6: Verify that address rotation changes IPv6 without triggering security alerts."""
        cur = self.conn.cursor()
        cur.execute("SELECT device_id, current_ipv6, current_pseudonym FROM devices WHERE tenant_id = 'tenant-alpha' LIMIT 1")
        dev = cur.fetchone()
        dev_id = dev["device_id"]
        old_ip = dev["current_ipv6"]

        # Count alerts prior to rotation
        cur.execute("SELECT COUNT(*) FROM security_alerts WHERE tenant_id = 'tenant-alpha'")
        alerts_before = cur.fetchone()[0]

        # Execute rotation
        res = self.simulator.rotate_device_address(self.conn, dev_id, "tenant-alpha")
        self.assertTrue(res["success"])
        new_ip = res["new_ipv6"]
        self.assertNotEqual(old_ip, new_ip, "Rotated IPv6 address must differ from the previous address.")

        # Verify no rogue alerts were generated by routine rotation
        cur.execute("SELECT COUNT(*) FROM security_alerts WHERE tenant_id = 'tenant-alpha'")
        alerts_after = cur.fetchone()[0]
        self.assertEqual(alerts_before, alerts_after, "Address rotation alone must not generate security alerts.")

if __name__ == "__main__":
    unittest.main()
